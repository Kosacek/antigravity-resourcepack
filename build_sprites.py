"""Perfectly round pool balls as camera-facing images ("impostors").

A sphere looks like a circle from every angle, so each ball is drawn as a flat
square model carrying a 128x128 picture of a shaded ball (soft lighting, gloss
highlight, stripe band, number circle). The server turns the ball entities to
always face the viewer (Display billboard CENTER), so they read as real spheres.

Usage:  python build_sprites.py <original pack folder> <output folder>
"""
import json
import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

NS = "swpool"
SIZE = 128
SS = 4                   # supersampling for smooth shading before the hard alpha edge
LIGHT = (-0.45, 0.55, 0.70)

POOL = {1: (240, 190, 20), 2: (22, 60, 165), 3: (205, 30, 40), 4: (86, 44, 136), 5: (242, 108, 28),
        6: (12, 118, 62), 7: (130, 30, 36), 8: (20, 20, 22)}
for _n in range(9, 16):
    POOL[_n] = POOL[_n - 8]
SNOOKER = {"red": (190, 20, 30), "yellow": (245, 200, 30), "green": (16, 112, 56), "brown": (112, 64, 32),
           "blue": (28, 66, 162), "pink": (238, 130, 170), "black": (20, 20, 22)}
WHITE = (247, 245, 238)
DOT = (200, 24, 32)


def _norm(v):
    length = math.sqrt(sum(c * c for c in v))
    return tuple(c / length for c in v)


L = _norm(LIGHT)
H = _norm((L[0], L[1], L[2] + 1.0))     # half vector for the specular highlight (viewer at +z)


def shade(base, n):
    diff = max(0.0, n[0] * L[0] + n[1] * L[1] + n[2] * L[2])
    spec = max(0.0, n[0] * H[0] + n[1] * H[1] + n[2] * H[2]) ** 60
    rim = 1.0 - 0.25 * (1.0 - n[2]) ** 2          # darken toward the silhouette
    k = (0.32 + 0.78 * diff) * rim
    return tuple(min(255, int(c * k + 255 * spec * 0.85)) for c in base)


def ball_image(colour_at, decals=()):
    """colour_at(nx, ny, nz) -> RGB for each point of the visible hemisphere."""
    big = SIZE * SS
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    px = img.load()
    r = big / 2.0 - 1
    for y in range(big):
        for x in range(big):
            nx, ny = (x + 0.5 - big / 2.0) / r, -(y + 0.5 - big / 2.0) / r
            d2 = nx * nx + ny * ny
            if d2 > 1.0:
                continue
            nz = math.sqrt(1.0 - d2)
            px[x, y] = shade(colour_at(nx, ny, nz), (nx, ny, nz)) + (255,)
    for draw_decal in decals:
        draw_decal(img)
    small = img.resize((SIZE, SIZE), Image.LANCZOS)
    # Hard alpha edge so the game's cutout rendering shows a clean circle
    a = small.split()[3].point(lambda v: 255 if v >= 128 else 0)
    small.putalpha(a)
    return small


def number_decal(n, font):
    def draw(img):
        big = img.width
        r = big * 0.21
        cx, cy = big / 2.0, big / 2.0
        layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=WHITE + (255,))
        text = str(n)
        box = d.textbbox((0, 0), text, font=font)
        w, h = box[2] - box[0], box[3] - box[1]
        d.text((cx - w / 2 - box[0], cy - h / 2 - box[1]), text, fill=(15, 15, 15, 255), font=font)
        # keep the sphere's lighting on the decal
        lp, ip = layer.load(), img.load()
        rr = big / 2.0 - 1
        for y in range(int(cy - r) - 1, int(cy + r) + 2):
            for x in range(int(cx - r) - 1, int(cx + r) + 2):
                p = lp[x, y]
                if p[3] == 0:
                    continue
                nx, ny = (x + 0.5 - big / 2.0) / rr, -(y + 0.5 - big / 2.0) / rr
                nz = math.sqrt(max(0.0, 1.0 - nx * nx - ny * ny))
                s = shade(p[:3], (nx, ny, nz))
                ip[x, y] = s + (255,)
    return draw


def build(src, out):
    models = os.path.join(out, "assets", NS, "models", "item")
    tex = os.path.join(out, "assets", NS, "textures", "item", "pool_sprite")
    os.makedirs(models, exist_ok=True)
    os.makedirs(tex, exist_ok=True)
    try:
        font = ImageFont.truetype("arialbd.ttf", int(SIZE * SS * 0.27))
    except OSError:
        font = ImageFont.load_default()

    with open(os.path.join(src, "assets", NS, "models", "item", "ball_md.json")) as fh:
        display = json.load(fh).get("display", {})

    def write(name, image):
        image.save(os.path.join(tex, name + ".png"))
        t = "%s:item/pool_sprite/%s" % (NS, name)
        e = 0.005
        model = {
            "credit": "Camera-facing pool ball for Pool and Billiards (Squid Workshop), generated by build_sprites.py",
            "textures": {"0": t, "particle": t},
            "elements": [{"from": [4, 4, 8 - e], "to": [12, 12, 8 + e], "shade": False,
                          "faces": {"south": {"uv": [0, 0, 16, 16], "texture": "#0"},
                                    "north": {"uv": [0, 0, 16, 16], "texture": "#0"}}}],
            "display": display,
        }
        with open(os.path.join(models, name + ".json"), "w") as fh:
            json.dump(model, fh, indent=1)

    for n in range(1, 16):
        base = POOL[n]
        if n >= 9:
            def colour(nx, ny, nz, base=base):
                return base if abs(ny) < 0.52 else WHITE
        else:
            def colour(nx, ny, nz, base=base):
                return base
        write("ball_%02d" % n, ball_image(colour, [number_decal(n, font)]))

    for name, rgb in SNOOKER.items():
        write(name, ball_image(lambda nx, ny, nz, rgb=rgb: rgb))

    def dotted(nx, ny, nz):
        for cx, cy in ((0.0, 0.0), (0.62, 0.55), (-0.7, -0.5)):
            if (nx - cx) ** 2 + (ny - cy) ** 2 < 0.018:
                return DOT
        return WHITE
    write("cueball", ball_image(dotted))
    write("cueball_clean", ball_image(lambda nx, ny, nz: WHITE))

    # preview sheet
    names = ["ball_%02d" % n for n in range(1, 16)] + ["cueball", "red", "yellow", "green", "brown", "blue",
                                                        "pink", "black"]
    sheet = Image.new("RGBA", (8 * 140, 3 * 140), (30, 100, 55, 255))
    for i, name in enumerate(names):
        im = Image.open(os.path.join(tex, name + ".png"))
        sheet.alpha_composite(im, ((i % 8) * 140 + 6, (i // 8) * 140 + 6))
    sheet.save(os.path.join(out, "..", "preview_sprites.png"))
    print("wrote %d sprite balls" % len(names))


if __name__ == "__main__":
    build(sys.argv[1], sys.argv[2])
